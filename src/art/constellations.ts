/** Перемешанная очередь; новая колода не начинается с того, чем кончилась прошлая. */
export function shuffledFigures(rand: () => number = Math.random, avoid?: SkyFigure): SkyFigure[] {
  const a = SKY_FIGURES.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  if (avoid && a[0] === avoid) a.push(a.shift()!);
  return a;
}

/** Радиус звезды в единицах кадра 0…100: ярче — крупнее. */
export function starRadius(mag: number): number {
  return Math.max(0.6, 2.2 - mag * 0.35);
}
